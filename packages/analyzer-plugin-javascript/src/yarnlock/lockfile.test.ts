import { describe, expect, test } from 'bun:test';
import { parsePackagePattern, resolvePackageVersion, findLineNumber, parseYarnLockfile } from './lockfile.ts';

describe('parsePackagePattern', () => {
  test('parses simple package pattern', () => {
    expect(parsePackagePattern('lodash@^4.17.21')).toEqual({ name: 'lodash', versionRange: '^4.17.21' });
  });

  test('parses scoped package pattern', () => {
    expect(parsePackagePattern('@babel/core@^7.0.0')).toEqual({ name: '@babel/core', versionRange: '^7.0.0' });
  });

  test('parses exact version pattern', () => {
    expect(parsePackagePattern('lodash@4.17.21')).toEqual({ name: 'lodash', versionRange: '4.17.21' });
  });

  test('returns null for pattern without @', () => {
    expect(parsePackagePattern('invalid')).toBeNull();
  });
});

describe('parseYarnLockfile', () => {
  test('parses a basic package entry', () => {
    const content = `lodash@^4.17.21:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz"
  integrity sha512-abc123
`;
    const lockfile = parseYarnLockfile(content);
    const pkg = lockfile.packages.get('lodash@^4.17.21');
    expect(pkg).toBeDefined();
    expect(pkg!.version).toBe('4.17.21');
    expect(pkg!.resolved).toBe('https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz');
    expect(pkg!.integrity).toBe('sha512-abc123');
  });

  test('parses multiple patterns for the same package', () => {
    const content = `lodash@^4.17.0, lodash@^4.17.21:
  version "4.17.21"
`;
    const lockfile = parseYarnLockfile(content);
    expect(lockfile.packages.get('lodash@^4.17.0')?.version).toBe('4.17.21');
    expect(lockfile.packages.get('lodash@^4.17.21')?.version).toBe('4.17.21');
  });

  test('parses scoped packages', () => {
    const content = `"@babel/core@^7.0.0":
  version "7.23.9"
`;
    const lockfile = parseYarnLockfile(content);
    expect(lockfile.packages.get('@babel/core@^7.0.0')?.version).toBe('7.23.9');
  });

  test('parses dependencies and optionalDependencies', () => {
    const content = `express@^4.18.0:
  version "4.18.2"
  dependencies:
    accepts "~1.3.8"
    body-parser "1.20.1"
  optionalDependencies:
    etag "~1.8.1"
`;
    const lockfile = parseYarnLockfile(content);
    const pkg = lockfile.packages.get('express@^4.18.0');
    expect(pkg!.dependencies).toEqual({ accepts: '~1.3.8', 'body-parser': '1.20.1' });
    expect(pkg!.optionalDependencies).toEqual({ etag: '~1.8.1' });
  });

  test('skips comment lines', () => {
    const content = `# THIS IS AN AUTOGENERATED FILE.

lodash@^4.17.21:
  version "4.17.21"
`;
    const lockfile = parseYarnLockfile(content);
    expect(lockfile.packages.size).toBe(1);
    expect(lockfile.packages.get('lodash@^4.17.21')?.version).toBe('4.17.21');
  });

  test('parses multiple package entries', () => {
    const content = `lodash@^4.17.21:
  version "4.17.21"

react@^18.0.0:
  version "18.2.0"
`;
    const lockfile = parseYarnLockfile(content);
    expect(lockfile.packages.size).toBe(2);
    expect(lockfile.packages.get('lodash@^4.17.21')?.version).toBe('4.17.21');
    expect(lockfile.packages.get('react@^18.0.0')?.version).toBe('18.2.0');
  });
});

describe('resolvePackageVersion', () => {
  const content = `lodash@^4.17.0, lodash@^4.17.21:
  version "4.17.21"

react@^18.0.0:
  version "18.2.0"
`;
  const lockfile = parseYarnLockfile(content);

  test('resolves version for an existing pattern', () => {
    expect(resolvePackageVersion(lockfile, 'lodash', '^4.17.21')).toBe('4.17.21');
  });

  test('resolves version for an alternative pattern', () => {
    expect(resolvePackageVersion(lockfile, 'lodash', '^4.17.0')).toBe('4.17.21');
  });

  test('returns null for unknown package', () => {
    expect(resolvePackageVersion(lockfile, 'unknown', '^1.0.0')).toBeNull();
  });
});

describe('findLineNumber', () => {
  const content = `# yarn lockfile v1

lodash@^4.17.21:
  version "4.17.21"

react@^18.0.0:
  version "18.2.0"
`;
  const lockfile = parseYarnLockfile(content);

  test('finds line number for a package', () => {
    expect(findLineNumber(content, lockfile, 'lodash', '4.17.21')).toBe(3);
  });

  test('finds line number for second package', () => {
    expect(findLineNumber(content, lockfile, 'react', '18.2.0')).toBe(6);
  });

  test('returns undefined for missing package', () => {
    expect(findLineNumber(content, lockfile, 'unknown', '1.0.0')).toBeUndefined();
  });
});
